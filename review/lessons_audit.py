"""Lesson audit (build plan Section 8.1). For each lesson L1-L12, locate quoted evidence in the paper sources and
write review/lessons-audit.md with file:line and the quoted sentence. A lesson whose evidence string is not found
is reported as BLOCKER. Evidence strings are fixed phrases from the paper text."""
import glob, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = sorted(glob.glob(os.path.join(ROOT, "paper", "sections", "*.tex"))) + [os.path.join(ROOT, "paper", "main.tex")]

L = [
    ("L1", "Enforcement guarantee is a labelled, conditional design guarantee, not a measurement",
     ["Design guarantee; holds by construction under A1--A4, not an empirical result",
      "The Remark is conditional and holds by construction; we do not count it as an experimental finding",
      "These attempts test, but cannot prove, assumption A1"]),
    ("L2", "Real-agent evaluation at scale (>=3 LLMs, >=2 frameworks, >=2 datasets, >=1,000 runs per main condition)",
     ["with frontier", "two agent frameworks", "BIRD and Spider"]),
    ("L3", "Load-bearing assumptions (inference quality, DB enforcement) in abstract and intro, quantified",
     ["The approach rests on two assumptions", "load-bearing assumption of the approach, and we quantify it directly",
      "Inference quality is the load-bearing assumption"]),
    ("L4", "What is not protected, in abstract and intro; positioned as reducing reachable data",
     ["TSE does not protect against inference from in-scope data", "TSE reduces the data reachable for a task; it does not prevent all leakage"]),
    ("L5", "Numeric comparisons only for systems run here; re-implementations labelled; conceptual table without numbers",
     ["Mechanism-level comparison as described by each work (no performance numbers; we did not run these systems)",
      "an approximation of curated per-role reporting schemas", "Baselines are approximations"]),
    ("L6", "Peer-reviewed anchors, DOIs, preprints with arXiv IDs (see review/refs-report.md for counts)",
     ["stonebraker1975query", "rizvi2004extending", "saltzer1975protection"]),
    ("L7", "Explicit technical delta vs query modification / FGAC",
     ["What is new relative to query modification and fine-grained access control",
      "Views, row-level security and query\nmodification are established techniques"]),
    ("L8", "Public tasks with gold SQL; policy-generation sensitivity; difficulty breakdown",
     ["The reduction is robust to the\npolicy generator", "Synthetic policies"]),
    ("L9", "Limitations, mitigations per failure mode, mechanism comparison, threat matrix (>=10 vectors)",
     ["Mitigations when the load-bearing assumptions fail", "Threat matrix. Evidence", "\\section{Limitations}"]),
    ("L10", "Abstract one paragraph within 150-250 words (checked by word count below)", ["\\begin{abstract}"]),
    ("L11", "No production-viability claims; secondary evaluations sized or labelled exploratory",
     ["We make no claim about production readiness", "(exploratory)", "exploratory arm with widening\ndenied"]),
    ("L12", "Candid limitations; automated number-consistency check",
     ["Benchmarks are not enterprise schemas", "Pre-freeze development and deviations"]),
]


def find(phrase):
    # match across line breaks: normalise whitespace in both
    norm = " ".join(phrase.split())
    for p in FILES:
        lines = open(p).read().split("\n")
        for i in range(len(lines)):
            window = " ".join(" ".join(lines[i:i + 3]).split())
            if norm in window and norm not in " ".join(" ".join(lines[i + 1:i + 3]).split()):
                return os.path.relpath(p, ROOT), i + 1
    return None


out = ["# Lesson audit (L1-L12)\n", "Generated by `review/lessons_audit.py` from the current paper sources.\n"]
blockers = 0
for lid, what, phrases in L:
    out.append(f"## {lid}: {what}\n")
    for ph in phrases:
        loc = find(ph)
        if loc:
            out.append(f"- `{loc[0]}:{loc[1]}`: \"{' '.join(ph.split())}\"")
        else:
            out.append(f"- **BLOCKER: not found**: \"{' '.join(ph.split())}\"")
            blockers += 1
    out.append("")
# abstract word count (after stripping LaTeX commands, macros count as one word)
import re
ab = open(os.path.join(ROOT, "paper", "sections", "abstract.tex")).read()
ab = re.sub(r"\\(begin|end)\{abstract\}", " ", ab)
words = len(re.sub(r"[{}\\~]", " ", ab).split())
out.append(f"## Abstract word count (approximate; macros count as one word): {words} (limit 150-250)\n")
if not 150 <= words <= 250:
    blockers += 1
out.append(f"\n**Blockers: {blockers}**\n")
open(os.path.join(ROOT, "review", "lessons-audit.md"), "w").write("\n".join(out))
print("blockers", blockers, "abstract words", words)
sys.exit(1 if blockers else 0)
